"""Generate flasher/patch_data.h (embedded byte patch + SHA-256s) from stock F05 and the built candidate."""
import hashlib,os
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
S=(ROOT/'extracted/AORUS_FO27Q3_F05/FWUPD/F05.bin').read_bytes()
C=(ROOT/os.environ.get('HOOK_OUT','experimental/FO27Q3_F05_HyperNits')/'F05_HyperNits.bin').read_bytes()
assert len(S)==len(C)
diff=[i for i in range(len(S)) if S[i]!=C[i]];runs=[];s=p=diff[0]
for i in diff[1:]:
    if i-p>16:runs.append((s,p+1));s=i
    p=i
runs.append((s,p+1))
o=['/* Generated by tools/make_flasher_patch_header.py. Do not edit. */','#include <stdint.h>',f'#define IMAGE_SIZE {len(S)}u',
 f'#define STOCK_SHA256 "{hashlib.sha256(S).hexdigest()}"',f'#define PATCHED_SHA256 "{hashlib.sha256(C).hexdigest()}"',f'#define RUN_COUNT {len(runs)}',
 'typedef struct{uint32_t off,len;const uint8_t*data;}run_t;']
for k,(a,b) in enumerate(runs):o.append(f'static const uint8_t run{k}[]={{'+','.join(map(str,C[a:b]))+'};')
o.append('static const run_t RUNS[RUN_COUNT]={'+','.join(f'{{{a}u,{b-a}u,run{k}}}' for k,(a,b) in enumerate(runs))+'};')
(ROOT/os.environ.get('HDR_OUT','flasher/patch_data.h')).write_text('\n'.join(o)+'\n');print(len(runs),'runs')
